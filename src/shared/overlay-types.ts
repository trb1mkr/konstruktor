// Общий контракт с��стемы оверлея: main <-> preload <-> renderer overlay.
// Единственный источник правды по формам сообщений. Никаких импортов из
// electron/vue — файл должен собираться в любом из трёх контекстов.

// Какие поверхности умеет показывать оверлей-окно. Renderer держит реестр
// view -> Vue-компонент, main — описание геометрии/фокуса.
//
// 'zoom' — попап масштаба у индикатора в адресной строке. Отдельный вид,
// а не меню с пунктом: форма своя (поле процента + кнопки), поведение
// своё — `+`/`−`/`Reset` НЕ закрывают попап, в отличие от пункта меню.
export type ViewKind =
  | 'menu'
  | 'dialog'
  | 'icon'
  | 'find'
  | 'toast'
  | 'window-menu'
  | 'zoom'

// Как меню выравнивается относительно точки вызова.
// 'anchor' — левый верхний угол в точке клика (контекстное меню).
// 'anchor-end' — правый край в точке (кнопка браузера).
// 'center' — по центру окна-родителя (диалоги).
// 'page-top-right' — правый верхний угол области страницы (панель поиска).
// 'page-bottom-right' — правый нижний угол области страницы (тосты).
//
// Оба считаются от границ ОКНА, а не монитора: оверлей принадлежит
// родителю, и в оконном режиме отсчёт от экрана уводил бы тост за
// пределы окна, под панель задач.
//
// Различаются только вертикалью, но разводить их пришлось: раньше оба
// сводились к 'page-top-right', и тост вставал по верху со сдвигом на
// высоту окна, а это работало только пока высота была константой.
// С измерением содержимого высота стала переменной, и позиция поплыла.
export type SurfaceAlign =
  | 'anchor'
  | 'anchor-end'
  | 'center'
  | 'page-top-right'
  | 'page-bottom-right'

// Описание поверхности: размеры, фокус, выравнивание, нужен ли focusable.
export interface Surface {
  // Ширина окна в px (menu/dialog фиксированы, у toast — максимум).
  width: number
  // Высота. null = измерить в renderer (высота зависит от числа пунктов).
  height: number | null
  align: SurfaceAlign
  // true = окно забирает фокус ввода (диалоги, поиск), иначе showInactive.
  focusable: boolean
  // Отступ от точки вызова, чтобы меню не липло к курсору.
  gap: number
}

// Пункт универсального меню. Один тип на все меню приложения:
// вкладки, группы, панель, меню браузера.
export interface MenuItem {
  id: string
  label: string
  // Эмодзи/символ или короткий текст. null = без иконки.
  icon?: string | null
  // Цвет группы (точка-индикатор), как на панели закладок.
  color?: string | null
  disabled?: boolean
  // Подпункты второго уровня (меню «Add to group» и т.п.).
  // null = пункт конечный.
  children?: MenuItem[] | null
  // Разделительная линия. Пункт не нажимается и не получает фокус:
  // в системном меню окна их три, и без них меню читается как сплошной
  // список, где непонятно, что «Свернуть» и «Закрыть» — разные вещи.
  separator?: boolean
}

// Данные для универсального диалога с полем ввода.
export interface DialogModel {
  title: string
  placeholder?: string
  initial?: string
  buttons: { id: string; label: string }[]
}

// Данные диалога иконки (URL / файл / эмодзи / отмена).
export interface IconModel {
  title: string
  placeholder?: string
  initial?: string
  // Ошибка верификации источника. Показывается под полем, диалог при этом
  // остаётся открытым. Приходит точечно через overlay:update: ошибку
  // видно раньше, чем пользователь успевает что-то изменить, и целиком
  // пересылать сессию ради неё незачем.
  error?: string
}

// Данные панели поиска.
export interface FindModel {
  query?: string
  // Счётчик совпадений. Не входит в push: он меняется на каждый ввод, и
  // гонять полную сессию ради одной строки значило бы пересоздавать
  // модель. Приходит точечно через overlay:update.
  counter?: string
}

// Данные тоста.
export interface ToastModel {
  title: string
  body?: string
  timeout?: number
}

// Данные попапа масштаба: текущий процент страницы.
//
// percent приходит и в push (открытие), и в overlay:update (каждое нажатие
// `+`/`−`): поле ввода живёт реактивно, а модель — единственный источник
// правды, из него же пересобирается badge в адресной строке через tabs:state.
export interface ZoomModel {
  percent: number
}

// Модель — то, что видно компоненту. Ровно одно поле заполнено
// (или items/itemsFor — для универсального меню любого контекста).
export type OverlayModel =
  | { view: 'menu'; items: MenuItem[]; badge?: string }
  // Своё меню окна (ПКМ по кнопкам навигации). Отдельный вид, а не флаг
  // у 'menu': у него другая геометрия (привязка к кнопкам окна, а не к
  // точке клика на странице) и он не должен закрываться тем же жестом,
  // что контекстные меню. Форма пунктов та же — MenuItem.
  | { view: 'window-menu'; items: MenuItem[] }
  | { view: 'dialog'; dialog: DialogModel }
  | { view: 'icon'; icon: IconModel }
  | { view: 'find'; find: FindModel }
  | { view: 'toast'; toast: ToastModel }
  | { view: 'zoom'; zoom: ZoomModel }

// Один уровень стека оверлея.
//
// Раньше PushMessage описывал одну сессию, и меню сменилось
// диалогом целиком: старое содержимое размонтировалось, новое занимало
// его место. Пользователь видел подмену, а не два уровня.
export interface StackEntry {
  sessionId: number
  model: OverlayModel
  // Меню прижато к точке вызова: меняет внутреннее выравнивание DOM.
  anchorLeft?: boolean
  // Положение уровня ВНУТРИ окна, в пикселях от его левого верхнего угла.
  //
  // Окно — объединение всех уровней, а не размер карточки: уровни
  // выровнены по-разному (меню у точки клика, диалог по центру, тост в
  // углу), и одним окном их показать можно только покрыв все целиком.
  // Renderer рисует уровни в потоке документа, поэтому каждому нужен
  // его сдвиг внутри окна — экранные координаты напрямую не годятся.
  //
  // Для ОДНОГО уровня offset равен нулю, иначе карточка уехала бы из
  // окна: при единственном уровне окно совпадает с самой карточкой.
  offset: { x: number; y: number }
  //
  // Размера здесь НЕТ намеренно. Окно шире отдельной карточки, и
  // соблазн задать рамке уровня width/height из сообщения очень велик.
  // Но ResizeObserver (единственный источник правды по размеру) наблюдает
  // именно рамку: зафиксированный размер делает её неизменной, наблюдатель
  // перестаёт срабатывать, и main никогда не получает замер. Вложенность
  // сломала измерение: в логе пропал 'bounds from measurement', и меню
  // оставалось запасного размера.
  //
  // Размер уровня задаёт СОДЕРЖИМОЕ рамки (обтекание), как и до стека.
}

// Что main сообщает renderer при открытии/смене сессии.
//
// Сессий в сообщении может быть несколько: показывается стек
// уровней, а не одну поверхность. order — снизу вверх, последний
// элемент рисуется сверху и сейчас на экране.
export interface PushMessage {
  // Стек уровней снизу вверх. Токен каждой сессии — sessionId
  // соответствующей записи, а не отдельное поле: при двух уровнях
  // одно общее поле sessionId означало бы, каким он помечен — верхним
  // или нижним, и поле пришлось бы угадывать.
  stack: StackEntry[]
  // Тема оверлея: 'dark' | 'light' | 'slate' (уже разрешена в main).
  theme: 'dark' | 'light' | 'slate'
  // Анимации включены (настройка). false = без fade.
  animations: boolean
}

// Точечное обновление живой сессии: счётчик поиска, ошибка валидации и т.п.
//
// Патч МЕРДЖИТСЯ в текущую модель, а не заменяет её: сессия одна, и
// приходит счётчик — значит view, тема и запрос остаются прежними.
// Замена целиком означала бы, что каждое обновление счётчика обязано
// тащить всю сессию, и преимущество канала над push исчезает.
export interface UpdateMessage {
  // Токен той сессии, к которой относится патч. Поздний патч от устаревшей
  // сессии обязан отбрасываться: иначе счётчик от прошлого поиска
  // появится в новом.
  sessionId: number
  // Глубокий частичный патч модели: { find: { counter } }, { icon: { error } }.
  patch: DeepPartial<OverlayModel>
}

// Команда renderer -> main: действие пользователя.
export type OverlayCommand =
  | { sessionId: number; type: 'select'; id: string }
  | { sessionId: number; type: 'submit'; value: string }
  | { sessionId: number; type: 'dismiss' }
  | { sessionId: number; type: 'find-query'; opts: FindQueryOptions }
  | { sessionId: number; type: 'find-next' }
  | { sessionId: number; type: 'find-prev' }
  | { sessionId: number; type: 'find-close' }
  // Диалог иконки: main верифицирует источник, false = ошибка в диалоге.
  | { sessionId: number; type: 'submit-icon'; buttonId: string; value: string }

export interface FindQueryOptions {
  query: string
  matchCase: boolean
  wholeWord: boolean
  useRegex: boolean
}

// Renderer сообщает реальные размеры содержимого после монтирования.
// Main корректирует bounds — окно никогда не режет меню.
export interface MeasureMessage {
  sessionId: number
  width: number
  height: number
}

// Рекурсивный Partial — для точечных патчей модели.
export type DeepPartial<T> = {
  [K in keyof T]?: T[K] extends object ? DeepPartial<T[K]> : T[K]
}

// Канал renderer -> main: пользователь нажал кнопку/пункт.
export const OVERLAY_CHANNELS = {
  command: 'overlay:command',
  measured: 'overlay:measured',
  // Подтверждение, что содержимое действительно убрано из DOM.
  //
  // Существует из-за измеренной особенности Linux: setOpacity там —
  // no-op, поэтому единственная защита от кадра со старым содержимым —
  // размонтирование через v-if. А setContentUnmounted уходит в renderer
  // асинхронным IPC, и setBounds с новыми координатами успевает
  // выполниться раньше. Без подтверждения окно на долю кадра показывало
  // прежнее меню в неверном месте — кнопку «Change icon», которая
  // открывает диалог, с видимым на его месте пунктом «Close».
  unmounted: 'overlay:unmounted'
} as const

